// { id, chapter, level, title, name, label, target } with target as 49
// characters; level counts from 1 inside each chapter. `name` is the
// title; `label` is the small line "Chapter N \u00b7 Level M".
const counts = {};
export const LEVELS = RAW.map(([chapter, title, ...rows], i) => {
  const level = (counts[chapter] = (counts[chapter] || 0) + 1);
  return {
    id: i,
    chapter,
    level,
    title,
    name: title,
    label: `Chapter ${chapter} \u00b7 Level ${level}`,
    target: rows.join(''),
  };
});
